import { ModelConverterResultOutput } from "./ModelConverterResultOutput";
import {Scene} from "../scene";
import {Data} from "../data";
import {ModelConverterReport} from "../../dist/xeoconvert/reporters/ModelConverterReporter";
import {ModelConverter} from "./ModelConverter";

/**
 * The result returned from a {@link ModelConverter.convert | ModelConverter.convert} operation.
 */
export interface ModelConverterResult {

    /**
     * The converter that created these results.
     */
    modelConverter: ModelConverter;


    scene: Scene;

    data: Data;

    /**
     * The pipeline identifier used during the conversion.
     */
    pipeline: string;

    /**
     * The inputs given to the conversion, keyed by input name as defined in the pipeline.
     */
    inputs: {
        [key: string]: any;
    };

    /**
     * The outputs generated by the conversion, keyed by output name as defined in the pipeline.
     */
    outputs: {
        [key: string]: ModelConverterResultOutput;
    };

    /**
     * The reports generated by the conversion, keyed by reporter ID.
     */
    reports: {
        [key: string]: ModelConverterReport;
    };
}
